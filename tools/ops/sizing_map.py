def collect_seats(live: bool) -> list[Row]:
    rows: list[Row] = []
    script = HOME / "bin" / "start-vllm-seat.sh"
    stext = _read(script)
    defaults = {"OMEN_MAX_MODEL_LEN": _grep(stext, r"OMEN_MAX_MODEL_LEN:-(\d+)", cast=int, default=16384),
                "OMEN_MAX_NUM_SEQS": _grep(stext, r"OMEN_MAX_NUM_SEQS:-(\d+)", cast=int, default=16),
                "OMEN_GPU_MEM_UTIL": _grep(stext, r"OMEN_GPU_MEM_UTIL:-([0-9.]+)", cast=float, default=0.82)}
    for k, v in defaults.items():
        rows.append(row("seat", f"script default {k}", v, _line_of(script, k + ":-"), "vLLM (any seat without a drop-in)",
                        "context / sequences / VRAM fraction", "applies when no drop-in sets it"))
    key = None
    if live:
        for line in _read(HOME / ".config" / "omen-vllm" / "omen-api.env").splitlines():
            if line.startswith("VLLM_API_KEY="):
                key = line.split("=", 1)[1].strip().strip('"')
    for seat in (0, 1):
        unit = f"omen-vllm@{seat}"
        try:
            env = subprocess.run(["systemctl", "--user", "show", unit, "-p", "Environment", "--value"],
                                 capture_output=True, text=True, timeout=10).stdout.split()
        except (OSError, subprocess.TimeoutExpired):
            env = []
        eff = {}
        for item in env:
            if item.startswith("OMEN_") and "=" in item and not re.search(r"(?:TOKEN|KEY|SECRET)$", item.partition("=")[0], re.I):   # credentials end in TOKEN/KEY; OMEN_MAX_BATCHED_TOKENS is a size
                k, _, v = item.partition("="); eff[k] = v
        dropins = sorted(p.name for p in (HOME / ".config" / "systemd" / "user" / f"{unit}.service.d").glob("*.conf"))
        src = f"~/.config/systemd/user/{unit}.service.d/{{{','.join(dropins)}}}"
        served = eff.get("OMEN_SERVED_NAME") or (Path(eff["OMEN_MODEL"]).name + " (served name = checkpoint dir)" if eff.get("OMEN_MODEL") else "")
        rows.append(row("seat", f"{unit} served model", served, src, f"HAProxy :{18091 + seat}", "which checkpoint answers"))
        mml = int(eff.get("OMEN_MAX_MODEL_LEN") or defaults["OMEN_MAX_MODEL_LEN"])
        rows.append(row("seat", f"{unit} max_model_len", mml, src, "vLLM", "input + output tokens per request"))
        seqs = int(eff.get("OMEN_MAX_NUM_SEQS") or defaults["OMEN_MAX_NUM_SEQS"])
        rows.append(row("seat", f"{unit} max_num_seqs", seqs, src if eff.get("OMEN_MAX_NUM_SEQS") else _line_of(script, "OMEN_MAX_NUM_SEQS:-"),
                        "vLLM scheduler", "concurrent sequences admitted", "" if eff.get("OMEN_MAX_NUM_SEQS") else "script default; no drop-in sets it"))
        rows.append(row("seat", f"{unit} gpu_memory_utilization", float(eff.get("OMEN_GPU_MEM_UTIL") or defaults["OMEN_GPU_MEM_UTIL"]), src, "vLLM", "VRAM fraction (weights + KV)"))
        if eff.get("OMEN_KV_CACHE_BYTES"):
            rows.append(row("seat", f"{unit} kv_cache_memory_bytes", int(eff["OMEN_KV_CACHE_BYTES"]), src, "vLLM", "fixed KV pool (overrides the utilisation for KV)"))
        rows.append(row("seat", f"{unit} attention_backend", eff.get("OMEN_ATTN_BACKEND") or "TRITON_ATTN", src if eff.get("OMEN_ATTN_BACKEND") else _line_of(script, "OMEN_ATTN_BACKEND:-"),
                        "vLLM", "attention kernel (prefill and decode rate at depth)", "" if eff.get("OMEN_ATTN_BACKEND") else "script default; no drop-in sets it"))
        for k, label in (("OMEN_MAX_BATCHED_TOKENS", "max_num_batched_tokens"), ("OMEN_PREFIX_MATCH_UNIT", "prefix_match_unit"), ("OMEN_MTP_K", "mtp_k")):
            if eff.get(k):
                rows.append(row("seat", f"{unit} {label}", int(eff[k]), src, "vLLM", {"max_num_batched_tokens": "prefill chunk", "prefix_match_unit": "prefix-hit granularity", "mtp_k": "speculative tokens"}[label]))
        # stale-comment and duplicate-key detectors on the drop-ins
        setters: dict[str, list[str]] = {}
        for name in dropins:
            text = _read(HOME / ".config" / "systemd" / "user" / f"{unit}.service.d" / name)
            for k in re.findall(r'^Environment="?(OMEN_[A-Z_]+)=', text, re.M):
                setters.setdefault(k, []).append(name)
            if re.search(r"staged", text, re.I) and name.endswith(".conf"):
                rows.append(row("seat", f"{unit} {name} says 'staged'", True, f"~/.config/systemd/user/{unit}.service.d/{name}", "operator", "misleading comment on an ACTIVE drop-in"))
        for k, names in sorted(setters.items()):
            if len(names) > 1:
                rows.append(row("seat", f"{unit} {k} set by {len(names)} drop-ins", " < ".join(names), f"~/.config/systemd/user/{unit}.service.d/", "systemd (last wins, alphabetical)", "the earlier file is dead configuration"))
        if live and key:
            try:
                req = urllib.request.Request(f"http://127.0.0.1:{18091 + seat}/v1/models", headers={"Authorization": f"Bearer {key}"})
                with urllib.request.urlopen(req, timeout=5) as r:
                    data = json.load(r)["data"]
                for m in data:
                    rows.append(row("seat-live", f"{unit} /v1/models", f"{m['id']} max_model_len={m.get('max_model_len')}", f"http://127.0.0.1:{18091 + seat}/v1/models", "clients", "live window"))
                req = urllib.request.Request(f"http://127.0.0.1:{18091 + seat}/metrics", headers={"Authorization": f"Bearer {key}"})
                with urllib.request.urlopen(req, timeout=5) as r:
                    metrics = r.read().decode("utf-8", "replace")
                m = re.search(r'^vllm:cache_config_info\{([^}]*)\}', metrics, re.M)
                if m:
                    labels = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
                    for k in ("kv_cache_size_tokens", "kv_cache_max_concurrency", "block_size", "cache_dtype"):
                        if k in labels:
                            v = labels[k]
                            v = int(v) if v.isdigit() else (round(float(v), 2) if re.fullmatch(r"[0-9.]+", v) else v)
                            rows.append(row("seat-live", f"{unit} {k}", v, f"http://127.0.0.1:{18091 + seat}/metrics cache_config_info", "vLLM", "KV pool" if "kv" in k else "block / dtype"))
            except Exception as exc:  # noqa: BLE001 -- live is best-effort
                rows.append(row("seat-live", f"{unit} live read", f"unavailable: {type(exc).__name__}", "", "", ""))
    if live:
        try:
            req = urllib.request.Request("http://127.0.0.1:18099/health")
            with urllib.request.urlopen(req, timeout=5) as r:
                data = json.load(r)
            rows.append(row("seat-live", "omen-perception health", f"status={data.get('status')} ips={data.get('images_per_second')}", "http://127.0.0.1:18099/health", "door", "CPU perception lane health"))
        except Exception as exc:  # noqa: BLE001
            rows.append(row("seat-live", "omen-perception live read", f"unavailable: {type(exc).__name__}", "", "", ""))
    return rows


def collect_router() -> list[Row]:
    path = HOME / ".config" / "omen-vllm" / "haproxy.cfg"
    text = _read(path)
    rows = [row("router", "haproxy global maxconn", _grep(text, r"^\s*maxconn\s+(\d+)", cast=int), _line_of(path, r"^\s*maxconn"), "haproxy", "total open connections")]
    for t in ("connect", "client", "server", "queue"):
        v = _grep(text, rf"^\s*timeout {t}\s+(\d+)s", cast=int)
        rows.append(row("router", f"haproxy timeout {t}", v, _line_of(path, rf"timeout {t}") if v is not None else _rel(path), "haproxy",
                        {"connect": "backend connect", "client": "idle per request (client side)", "server": "idle per request (seat side)", "queue": "wait for a free server slot"}[t],
                        "" if v is not None else "not set"))
    for fe, port in re.findall(r"frontend (\w+)\n\s+bind 127\.0\.0\.1:(\d+)", text):
        rows.append(row("router", f"frontend {fe}", int(port), _line_of(path, f"frontend {fe}"), "HEARTH rung endpoint", "which lane a port is"))
    for be, body in re.findall(r"backend (\w+)\n((?:\s+.*\n)+)", text):
        servers = re.findall(r"server (\w+) 127\.0\.0\.1:(\d+)([^\n]*)", body)
        for name, port, rest in servers:
            mc = _grep(rest, r"maxconn (\d+)", cast=int)
            rows.append(row("router", f"backend {be} server {name}", f"127.0.0.1:{port}" + (f" maxconn {mc}" if mc else " (no maxconn)"), _line_of(path, f"server {name}"), "haproxy", "seat behind the lane; per-server maxconn queues overflow at the router", "" if mc else "no per-server maxconn: overflow queues inside vLLM"))
    return rows


def _toml(path: Path) -> dict:
    try:
        return tomllib.loads(_read(path))
    except (tomllib.TOMLDecodeError, OSError):
        return {}


def collect_backends() -> list[Row]:
    path = Path(os.environ.get("HEARTH_BACKENDS", str(PROD / "backends-linux.toml")))
    doc = _toml(path)
    rows = [row("rung", "default rung", doc.get("default"), _line_of(path, "^default"), "local_generate", "where untagged calls land")]
    for b in doc.get("backend", []):
        s = b.get("settings", {})
        name = b["name"]
        for k, bounds in (("context_tokens", "input + output tokens the seat holds"), ("context_bytes", "payload bytes admitted by the door (3.5 B/token, no output reserve)"),
                          ("max_tokens", "default output budget = the reserve local-work subtracts"), ("deliberate_max_tokens", "largest output a streamed inference.deliberate turn may ask for on this rung"), ("timeout_s", "HTTP timeout when the caller sets none (execution path always overrides)"),
                          ("parallel_slots", "HEARTH lease slots on this rung"),
                          ("flash_attention", "declared attention backend of the seat (true = FLASH_ATTN)"),
                          ("speculative", "declared MTP draft depth of the seat (mtp-k<N>)"),
                          ("images_per_second", "measured perception throughput on CPU"),
                          ("max_image_bytes", "largest image payload accepted")):
            if k in s:
                rows.append(row("rung", f"{name} {k}", s[k], _line_of(path, rf"^\s*{k}\s*=") , "backends pool", bounds))
        rows.append(row("rung", f"{name} endpoint", b.get("endpoint"), _line_of(path, f'name = "{name}"'), "door", "which router port"))
    text = _read(path)
    m = re.search(r"KV pool[^\n]*?(\d{2},\d{3}|\d{5})[^\n]*tokens", text)
    if m:
        rows.append(row("rung", "backends-linux.toml KV-pool comment", m.group(1).replace(",", ""), _line_of(path, r"KV pool"), "operator", "documentation of the dense seat's KV pool", "compared against the live kv_cache_size_tokens under --live"))
    return rows


def collect_routes_and_families() -> list[Row]:
    rows: list[Row] = []
    rp = Path(os.environ.get("HEARTH_LOCAL_WORK_ROUTES", str(PROD / "local-work-routes-linux.toml")))
    for lane, spec in _toml(rp).get("lane", {}).items():
        rows.append(row("local-work", f"lane {lane}", spec.get("backend"), _line_of(rp, rf"\[lane\.{lane}\]"), "submit_local_work", "which rung a lane is"))
    fp = Path(os.environ.get("HEARTH_ROUTING_FAMILIES", str(PROD / "routing-families-linux.toml")))
    fam = _toml(fp).get("family", {})
    for name, spec in sorted(fam.items()):
        if spec.get("refusal"):
            rows.append(row("family", f"family {name}", f"refusal: {spec['refusal']}", _line_of(fp, rf"\[family\.{name}\]"), "door refusal", "explicit refusal (missing capability)"))
            continue
        d = spec.get("depth_override") or {}
        val = f"{spec.get('model_id')}"
        if d.get("min_prompt_tokens"):
            val += f"; >= {d['min_prompt_tokens']} prompt tokens -> {d.get('model_id')}"
        if spec.get("min_prompt_tokens"):
            val += f"; >= {spec['min_prompt_tokens']} -> {spec.get('model_id')} else {spec.get('below_threshold_model_id')}"
        if spec.get("tags"):
            val += f"; tags {spec['tags']}"
        rows.append(row("family", f"family {name}", val, _line_of(fp, rf"\[family\.{name}\]"), "families.recommend (advisory) / local_generate tag route", "model + depth threshold (prompt tokens = payload bytes // 4)"))
    return rows


def collect_operations() -> list[Row]:
    path = Path(os.environ.get("HEARTH_OPERATIONS", str(REPO / "hearth" / "etc" / "operations.toml")))
    doc = _toml(path)
    rows = []
    for op, spec in doc.get("operation", {}).items():
        if op not in ("llm.chat", "inference.generate", "inference.deliberate", "work.produce"):
            continue
        if spec.get("streamed"):
            rows.append(row("operation", f"{op} streamed", True, _line_of(path, rf'\[operation\."{re.escape(op)}"\]'), "execution policy_for", "submit/watch only; the router's idle timers do not bound its deadline"))
        for k, bounds in (("max_tokens_ceiling", "largest output budget a job may ask for"), ("deadline_ceiling_s", "largest deadline; also the default when none is given"), ("max_prompt_bytes", "largest prompt")):
            rows.append(row("operation", f"{op} {k}", spec.get(k), _line_of(path, rf'\[operation\."{re.escape(op)}"\]'), "execution policy_for", bounds))
    return rows


