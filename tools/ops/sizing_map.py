Row = dict[str, Any]


def row(layer: str, setting: str, value: Any, source: str, consumer: str, bounds: str, note: str = "") -> Row:
    return {"layer": layer, "setting": setting, "value": value, "source": source, "consumer": consumer,
            "bounds": bounds, "note": note}


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
    except OSError:
        return ""


def _grep(text: str, pattern: str, group: int = 1, cast: Callable = str, default=None):
    m = re.search(pattern, text, re.MULTILINE)
    if not m:
        return default
    try:
        return cast(m.group(group))
    except (TypeError, ValueError):
        return default


def _line_of(path: Path, pattern: str) -> str:
    text = _read(path)
    for i, line in enumerate(text.splitlines(), 1):
        if re.search(pattern, line):
            return f"{_rel(path)}:{i}"
    return _rel(path)


def _rel(path: Path) -> str:
    p = str(path)
    for base, name in ((str(REPO), "repo"), (str(HOME), "~")):
        if p.startswith(base):
            return name + p[len(base):]
    return p


