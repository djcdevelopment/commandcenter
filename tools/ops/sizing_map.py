def collect_measured() -> list[Row]:
    """p90 of the dense lane's work.produce runs from the execution ledger (aggregates only)."""
    path = PROD / "var" / "execution" / "events.ndjson"
    outs, durs = [], []
    try:
        with path.open("rb") as fh:
            for raw in fh:
                if b'"invocation.succeeded"' not in raw or b'"work.produce"' not in raw and b'omen-dense-27b' not in raw:
                    continue
                try:
                    e = json.loads(raw)
                except ValueError:
                    continue
                if e.get("event_type") != "invocation.succeeded":
                    continue
                o = e.get("observed") or {}
                if o.get("backend") != "omen-dense-27b":
                    continue
                if o.get("tokens_out") and o.get("duration_ms"):
                    outs.append(int(o["tokens_out"])); durs.append(int(o["duration_ms"]))
    except OSError:
        return []
    if not outs:
        return []
    rate = [1000.0 * o / d for o, d in zip(outs, durs) if d]
    rate.sort(); outs.sort(); durs.sort()
    p90 = lambda xs: xs[min(len(xs) - 1, int(0.9 * (len(xs) - 1)))]  # noqa: E731
    return [row("measured", "omen-dense-27b invocations (n)", len(outs), _rel(path), "sizing rules", "sample"),
            row("measured", "omen-dense-27b tokens_out p90 / max", f"{p90(outs)} / {outs[-1]}", _rel(path), "", "how close outputs come to the cap"),
            row("measured", "omen-dense-27b duration_ms p90 / max", f"{p90(durs)} / {durs[-1]}", _rel(path), "", "how close jobs come to the deadline"),
            row("measured", "omen-dense-27b decode tok/s median", round(rate[len(rate) // 2], 1), _rel(path), "deadline derivation", "output / duration (prefill included, so a floor)")]


