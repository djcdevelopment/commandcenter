def _val(rows: list[Row], setting: str, default=None):
    for r in rows:
        if r["setting"] == setting:
            return r["value"]
    return default


def _num(v, default=None):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def invariants(rows: list[Row]) -> list[dict]:
    """Each rule cites the observation that earned it. Returns the violations."""
    out: list[dict] = []
    def fail(rule: str, detail: str, earned_by: str):
        out.append({"rule": rule, "detail": detail, "earned_by": earned_by})
    rungs = {}
    for r in rows:
        if r["layer"] == "rung" and " " in r["setting"]:
            name, key = r["setting"].split(" ", 1); rungs.setdefault(name, {})[key] = r["value"]
    seat_for = {"omen-vllm": "omen-vllm@1", "omen-dense-27b": "omen-vllm@0",
                "omen-dense-27b-b": "omen-vllm@1"}
    # Declarations for mutually exclusive profiles coexist in the pool. Only compare
    # a backend with its occupied seat, while keeping absent-route checks below.
    active_cfg = _val(rows, "active configuration")
    for rung, seat in list(seat_for.items()):
        status = str(_val(rows, f"config {active_cfg} backend {rung}", ""))
        served = str(_val(rows, f"{seat} served model", ""))
        if "status=absent" in status:
            del seat_for[rung]
        elif "status=live" not in status and served:
            expected = "qwen3-30b-a3b" if rung == "omen-vllm" else "qwen3.8-27b"
            if expected not in served:
                del seat_for[rung]
    # 1. rung context == seat window
    for rung, seat in seat_for.items():
        s = rungs.get(rung, {}); mml = _val(rows, f"{seat} max_model_len")
        if s.get("context_tokens") is not None and mml is not None and int(s["context_tokens"]) != int(mml):
            fail("rung-context-equals-seat-window", f"{rung} context_tokens {s['context_tokens']} != {seat} max_model_len {mml}", "the 30B seat refused 65536 at startup (07-serving-recipe.md); the declaration must be the seat's")
    # 2. max_num_seqs >= parallel_slots and slots x typical <= KV
    for rung, seat in seat_for.items():
        s = rungs.get(rung, {}); seqs = _num(_val(rows, f"{seat} max_num_seqs")); slots = _num(s.get("parallel_slots"))
        if seqs is not None and slots is not None and seqs < slots:
            fail("seat-admits-at-least-the-leases", f"{seat} max_num_seqs {seqs:g} < {rung} parallel_slots {slots:g}", "leases would queue on a seat that cannot admit them")
        kv = _num(_val(rows, f"{seat} kv_cache_size_tokens"))
        if kv is not None and slots is not None and s.get("context_tokens") is not None and s.get("max_tokens") is not None:
            # A realistic concurrent request: measured p90 input on the dense lane was 19.5K of a
            # 65,536 window (0.30) and p90 output 5.7K of a 16,384 reserve; half the reserve is the
            # conservative allowance. vLLM preempts when the pool is exhausted, so the sum must fit.
            typical = 0.30 * float(s["context_tokens"]) + 0.5 * float(s["max_tokens"])
            if slots * typical > kv:
                fail("slots-fit-the-kv-pool", f"{rung}: {slots:g} slots x typical {typical:.0f} tokens = {slots * typical:.0f} > {seat} KV pool {kv:.0f}", "a work.produce waited 9.3 s for a slot on 2026-09-27 at 3 slots; preemption follows oversubscription")
    # 2b. a rung's declared recipe is the seat's (the serving profile in a capability record is the declaration)
    for rung, seat in seat_for.items():
        s = rungs.get(rung, {}); attn = _val(rows, f"{seat} attention_backend"); k = _val(rows, f"{seat} mtp_k")
        if s and attn is not None and bool(s.get("flash_attention")) != (attn == "FLASH_ATTN"):
            fail("declared-recipe-is-the-seat", f"{rung} flash_attention {s.get('flash_attention')} but {seat} attention_backend {attn}", "the 27B ran 4 to 20 times faster on Flash (2026-10-03); a record that hides the backend mixes two configurations")
        if s.get("speculative") is not None and str(s["speculative"]) != f"mtp-k{k}":
            fail("declared-recipe-is-the-seat", f"{rung} speculative {s['speculative']} but {seat} mtp_k {k}", "the declared draft depth must be the seat's")
    # 3. operation ceilings vs rungs
    ceil = {}
    for r in rows:
        if r["layer"] == "operation" and r["setting"].endswith(" max_tokens_ceiling"):
            ceil[r["setting"].split(" ")[0]] = _num(r["value"])
    max_reserve = max((_num(s.get("max_tokens"), 0) for s in rungs.values()), default=0)
    max_deliberate = max((_num(s.get("deliberate_max_tokens"), 0) for s in rungs.values()), default=0)
    for op, c in ceil.items():
        reserve = max_deliberate if op == "inference.deliberate" else max_reserve
        if c and c > reserve and (reserve or op == "inference.deliberate"):
            fail("operation-ceiling-within-the-largest-rung-reserve", f"{op} max_tokens_ceiling {c:g} > largest rung {'deliberate_max_tokens' if op == 'inference.deliberate' else 'max_tokens'} {reserve:g}", "a rung's max_tokens is what its seat is declared to serve as output; an operation that allows more admits a request no seat can complete (a 32,768 output on the 40,960 seat leaves 8K for input)")
    wp = ceil.get("work.produce")
    dense = rungs.get("omen-dense-27b", {})
    if wp and dense.get("max_tokens") is not None and _num(dense["max_tokens"]) > wp:
        fail("rung-reserve-within-ceiling", f"omen-dense-27b max_tokens {dense['max_tokens']} > work.produce ceiling {wp:g}", "a submit at the rung's own default would be refused at the ceiling")
    # 4. admission reserves output
    if _val(rows, "payload admission rule (pin and tag route)") == "payload_bytes <= context_bytes":
        fail("door-admission-reserves-output", "local_generate admits payload <= context_bytes and reserves nothing for max_tokens", "the pinned-rung refusal exists to fail at the door, not the server; today a full payload plus the default output overflows omen-vllm (40,960 + 8,192), am4 (16,384 + 8,192) and fx99 (4,096 + 2,048)")
    # 5. deadlines and timeouts chain
    dl = _num(_val(rows, "work.produce deadline_ceiling_s")); rate = _num(_val(rows, "omen-dense-27b decode tok/s median"))
    if dl and wp and rate:
        need = wp / rate + 60
        if need > dl:
            fail("deadline-covers-the-output", f"work.produce ceiling {wp:g} tokens at {rate:g} tok/s needs ~{need:.0f} s > deadline_ceiling_s {dl:g}", "the 5,690-token candidate took 545 s on 2026-09-27; a full 8,192 needs ~790 s + prefill")
    sub_dl = _num(_val(rows, "submit_local_work deadline_s default"))
    if sub_dl and dl and sub_dl < dl:
        pass  # a lower default than the ceiling is allowed; recorded in the table
    # Every operation's deadline, not only work.produce's. A streamed operation is submit/watch and its router
    # timers are idle timers (each chunk resets them), so it is bounded by none of these client timeouts.
    for op in sorted(r["setting"].rsplit(" ", 1)[0] for r in rows if r["layer"] == "operation" and r["setting"].endswith(" deadline_ceiling_s")):
        op_dl = _num(_val(rows, f"{op} deadline_ceiling_s"))
        if _val(rows, f"{op} streamed") or not op_dl:
            continue
        for who, key, scale in (("haproxy timeout server", "haproxy timeout server", 1), ("codex mcp tool_timeout_sec", "codex mcp tool_timeout_sec", 1), ("claude code hearth timeout (ms)", "claude code hearth timeout (ms)", 1000)):
            v = _num(_val(rows, key))
            if v is not None and v / scale < op_dl:
                fail("client-timeouts-cover-the-deadline", f"{op}: {who} {v:g}{'ms' if scale == 1000 else 's'} < deadline_ceiling_s {op_dl:g}", "a door call that outlives its client timeout is reported as a client error, not a result")
    if str(_val(rows, "gateway tool dispatch", "")).startswith("on the event loop"):
        fail("door-serves-calls-concurrently", "hearth-production.service runs the gateway without --threaded-tools", "2026-09-28 00:54Z: eight parallel local_generate pins to the 8-slot MoE lane completed 5 s apart; the seat never saw more than one request")
    if _val(rows, "haproxy timeout queue") is None:
        fail("router-queues-overflow", "haproxy has no per-server maxconn and no timeout queue", "with max_num_seqs 16 on both seats, the 17th request waits inside vLLM with no router-side bound")
    # 6. runner budgets vs route
    for name, rung in (("omen", "omen-vllm"), ("omen-dense", "omen-dense-27b")):
        rc = _num(_val(rows, f"ROUTES.{name}.context")); sc = _num(rungs.get(rung, {}).get("context_tokens"))
        if rc is not None and sc is not None and rc != sc:
            fail("runner-context-equals-seat", f"ROUTES.{name}.context {rc:g} != {rung} context_tokens {sc:g}", "the runner's own context check and summarization trigger use this number")
    rd = _num(_val(rows, "RequestBudget deadline (s)")); wt = _num(_val(rows, "RUN_TIMEOUT_S (wrapper)"))
    if rd and wt and wt < rd + 60:
        fail("wrapper-outlives-the-runner", f"RUN_TIMEOUT_S {wt:g} < runner deadline {rd:g} + 60", "a wrapper that kills first leaves no result.json")
    ev = _num(_val(rows, "tool_token_limit_before_evict")); dctx = _num(_val(rows, "ROUTES.omen-dense.context"))
    if ev is not None and dctx and ev < dctx / 16:
        fail("eviction-scales-with-context", f"tool_token_limit_before_evict {ev:g} < ROUTES.omen-dense.context / 16 ({dctx / 16:.0f})", "2026-09-27 retry: a 1,500-token preview cap on a 65K lane produced 12 read-only calls and 5 evicted files, and the attempt budget ran out")
    guard = str(_val(rows, "transport output guard", ""))
    if "max_completion_tokens" not in guard:
        fail("guard-reads-the-field-langchain-sends", f"transport output guard {guard}", "measured 2026-09-27: every request carried max_completion_tokens=3072 and the guard checked a default 2048")
    # 6b. AM4 profile rungs
    for rung, seat in (("am4-tool-4070ti", "am4-tool@4070ti"), ("am4-tool-5070", "am4-tool@5070")):
        s_ = rungs.get(rung, {}); mml = _val(rows, f"{seat} max_model_len")
        if s_.get("context_tokens") is not None and mml is not None and int(s_["context_tokens"]) != int(mml):
            fail("am4-rung-context-equals-seat-window", f"{rung} context_tokens {s_['context_tokens']} != {seat} max_model_len {mml}", "the AM4 tool seats declare their window in seat-*.env; the rung must repeat it exactly")
        rc = _num(_val(rows, f"ROUTES.{rung}.context")); 
        if rc is not None and mml is not None and rc != float(mml):
            fail("runner-context-equals-seat", f"ROUTES.{rung}.context {rc:g} != {seat} max_model_len {mml}", "the runner's own context check uses this number")
    prof = _val(rows, "am4 profile")
    if prof in ("dense-tp2", "tool-pair"):
        expected = {"dense-tp2": ["am4-dense-27b"], "tool-pair": ["am4-tool-4070ti", "am4-tool-5070"]}[prof]
        for alias in ("am4-dense-27b", "am4-tool-4070ti", "am4-tool-5070"):
            rdy = _val(rows, f"facade alias {alias} ready")
            if rdy is None or isinstance(rdy, str):
                continue
            if (alias in expected) != bool(rdy):
                fail("am4-profile-aliases-served", f"profile {prof}: alias {alias} ready={rdy}", "one profile is live at a time; an alias ready outside its profile means the switch left a seat running (or the profile file lies)")
    # 6c. the request sizer (ADR-0050)
    gate = str(_val(rows, "HEARTH_SIZER gate (hearth-ops.env)", "unset (off)"))
    if gate not in ("off", "heuristic", "npu", "unset (off)"):
        fail("sizer-gate-is-a-known-mode", f"HEARTH_SIZER={gate}", "an unknown value reads as off silently; the operator meant something else")
    long_rungs = {x.strip() for x in str(_val(rows, "rungs tagged tool-long", "")).split(",") if x.strip() and x.strip() != "none"}
    if long_rungs and long_rungs != {"am4-tool-5070"}:
        fail("tool-long-only-on-the-decode-seat", f"rungs tagged tool-long: {sorted(long_rungs)}", "the tag exists to put l/xl output on the faster decoder; a second carrier makes the split a coin toss")
    bins = str(_val(rows, "output bins (upper edge, tokens)", ""))
    xl_edge = _num(bins.rsplit(">=", 1)[-1]) if ">=" in bins else None
    for rung in long_rungs:
        mt = _num(rungs.get(rung, {}).get("max_tokens"))
        if xl_edge and mt is not None and mt < xl_edge:
            fail("long-rung-budget-covers-the-xl-bin", f"{rung} max_tokens {mt:g} < xl bin edge {xl_edge:g}", "the sizer sends xl output here; a rung budget below the edge truncates what the sizer promised room for")
    # 6d. perception lane invariants (task 13)
    perc = rungs.get("omen-perception")
    if perc:
        ips = _num(perc.get("images_per_second"))
        mib = _num(perc.get("max_image_bytes"))
        if ips is None or ips <= 0:
            fail("perception-declares-throughput", "omen-perception missing images_per_second or <= 0", "perception lane declares images_per_second instead of context_tokens")
        if mib is None or mib <= 0:
            fail("perception-declares-max-image-bytes", "omen-perception missing max_image_bytes or <= 0", "perception lane declares max_image_bytes instead of context_bytes")
    # 7. stale comments
    for r in rows:
        if r["setting"].endswith("says 'staged'") and r["value"] is True:
            fail("active-drop-in-says-staged", r["source"], "an operator reading the drop-in dir cannot tell what is live")
        if " set by " in r["setting"] and "drop-ins" in r["setting"]:
            fail("one-drop-in-per-key", f"{r['setting']}: {r['value']}", "seat 0's max-model-len.conf (40960) is overridden by stage2-27b-mtp.conf (65536); its comment describes the other checkpoint")
    kv_comment = _num(_val(rows, "backends-linux.toml KV-pool comment")); kv_live = _num(_val(rows, "omen-vllm@0 kv_cache_size_tokens"))
    if kv_comment and kv_live and abs(kv_comment - kv_live) > 0.25 * kv_live:
        fail("kv-comment-matches-live", f"backends-linux.toml says KV pool {kv_comment:.0f}; live seat 0 reports {kv_live:.0f}", "the pool varies per start (76,706 and 99,048 seen on the same config, 2026-09-27); the comment must say so and stay within 25%")
    # 8. Whole-lab configuration invariants (ADR-0052, task 8)
    active_cfg = _val(rows, "active configuration")
    if active_cfg is not None and not str(active_cfg).startswith("unprobed"):
        omen_p = _val(rows, "active omen profile")
        am4_p = _val(rows, "active am4 profile")
        if active_cfg == "unknown" or not active_cfg:
            fail("active-configuration-detected",
                 f"no lab configuration matches active profiles (omen={omen_p}, am4={am4_p})",
                 "every operating state of the lab must be a named configuration in host/lab-configurations.toml (ADR-0052, task 8)")
        else:
            expected_live: set[str] = set()
            expected_absent: set[str] = set()
            cfg_prefix = f"config {active_cfg} backend "
            for r in rows:
                if r["layer"] == "configuration" and r["setting"].startswith(cfg_prefix):
                    bname = r["setting"][len(cfg_prefix):]
                    val_str = str(r["value"])
                    if "status=live" in val_str:
                        expected_live.add(bname)
                    elif "status=absent" in val_str:
                        expected_absent.add(bname)

            # Expected live backends must be serving
            for b in sorted(expected_live):
                if b == "omen-vllm":
                    s1_live = _val(rows, "omen-vllm@1 live read")
                    s1_models = _val(rows, "omen-vllm@1 /v1/models")
                    if s1_live and "unavailable" in str(s1_live):
                        fail("expected-live-backends-serving", f"omen-vllm expected live under {active_cfg} but seat 1 is unavailable: {s1_live}", "live backends must be UP and responding to /v1/models")
                    elif s1_models is None and s1_live is not None:
                        fail("expected-live-backends-serving", f"omen-vllm expected live under {active_cfg} but seat 1 is not serving", "live backends must be UP and responding to /v1/models")
                elif b in ("omen-dense-27b", "omen-dense-27b-b"):
                    seat = 0 if b == "omen-dense-27b" else 1
                    live_read = _val(rows, f"omen-vllm@{seat} live read")
                    models = _val(rows, f"omen-vllm@{seat} /v1/models")
                    if live_read and "unavailable" in str(live_read):
                        fail("expected-live-backends-serving", f"{b} expected live under {active_cfg} but seat {seat} is unavailable: {live_read}", "live backends must be UP and responding to /v1/models")
                    elif (models is not None and "qwen3.8-27b" not in str(models)) or (models is None and live_read is not None):
                        fail("expected-live-backends-serving", f"{b} expected live under {active_cfg} but seat {seat} is serving {models}", "live backends must serve their declared model")
                elif b in ("am4-vllm", "am4-tool-4070ti", "am4-tool-5070"):
                    alias = "am4-dense-27b" if b == "am4-vllm" else b
                    rdy = _val(rows, f"facade alias {alias} ready")
                    if rdy is not None and rdy is not True:
                        fail("expected-live-backends-serving", f"{b} expected live under {active_cfg} but facade alias {alias} ready={rdy}", "live backends must report ready=True on their facade alias")
                elif b == "omen-perception":
                    p_live = _val(rows, "omen-perception live read")
                    if p_live and "unavailable" in str(p_live):
                        fail("expected-live-backends-serving", f"omen-perception expected live under {active_cfg} but perception service is unavailable: {p_live}", "live backends must be UP and responding to /health")

            # Expected absent backends must not be routable
            for b in sorted(expected_absent):
                if _val(rows, "default rung") == b:
                    fail("expected-absent-backends-not-routable", f"backend {b} expected absent under {active_cfg} but is default rung", "untagged requests fall through to the default rung")
                for r in rows:
                    if r["layer"] == "local-work" and r["setting"].startswith("lane ") and r["value"] == b:
                        lane_name = r["setting"]
                        fail("expected-absent-backends-not-routable", f"backend {b} expected absent under {active_cfg} but pinned by {lane_name}", "local-work lanes must not pin absent backends")
                if b in ("am4-vllm", "am4-tool-4070ti", "am4-tool-5070"):
                    alias = "am4-dense-27b" if b == "am4-vllm" else b
                    rdy = _val(rows, f"facade alias {alias} ready")
                    if rdy is True:
                        fail("expected-absent-backends-not-routable", f"backend {b} expected absent under {active_cfg} but facade alias {alias} ready=True", "an absent backend must not be ready in the facade")
                if b == "omen-dense-27b":
                    if any(r["layer"] == "rung" and r["setting"].startswith("omen-dense-27b ") for r in rows):
                        fail("expected-absent-backends-not-routable", f"backend {b} expected absent under {active_cfg} but declared in backends pool with tags and no occupancy probe", "an absent backend on OMEN without an occupancy probe accepts tag traffic")

            # Routing families must not resolve to absent backends
            for r in rows:
                if r["layer"] != "family":
                    continue
                fam_name = r["setting"].split("family ", 1)[1]
                fam_val = str(r["value"])
                if "refusal:" in fam_val or fam_name in ("document_ocr", "chart_diagram", "screenshot_grounded"):
                    continue

                resolved_backend: Optional[str] = None
                if fam_name in ("code_fix", "code_review", "long_review", "quote_retrieval"):
                    resolved_backend = "omen-dense-27b"
                elif fam_name in ("tool_execution",):
                    ti_ready = _val(rows, "facade alias am4-tool-4070ti ready") is True and "am4-tool-4070ti" not in expected_absent
                    s5_ready = _val(rows, "facade alias am4-tool-5070 ready") is True and "am4-tool-5070" not in expected_absent
                    if ti_ready:
                        resolved_backend = "am4-tool-4070ti"
                    elif s5_ready:
                        resolved_backend = "am4-tool-5070"
                    else:
                        resolved_backend = _val(rows, "default rung") or "omen-vllm"
                elif fam_name in ("tool_long_output",):
                    s5_ready = _val(rows, "facade alias am4-tool-5070 ready") is True and "am4-tool-5070" not in expected_absent
                    resolved_backend = "am4-tool-5070" if s5_ready else (_val(rows, "default rung") or "omen-vllm")
                elif fam_name in ("utility_text",):
                    resolved_backend = "fx99-vllm"
                else:
                    resolved_backend = _val(rows, "default rung") or "omen-vllm"

                if resolved_backend in expected_absent:
                    fail("routing-families-resolve-to-live-backends",
                         f"family {fam_name} resolves to absent backend {resolved_backend}",
                         "routing a family to an absent backend produces 500s or hangs (as happened on 2026-09-27)")
    return out


